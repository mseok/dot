#!/usr/bin/env bash
# Install the repository-managed Codex surface without copying host-local state.
#
# Managed by this script:
#   $CODEX_HOME/AGENTS.md
#   $CODEX_HOME/rules/hpc.rules (Linux/HPC only)
#   individual user skills below $CODEX_HOME/skills/
#
# Deliberately not managed here:
#   config.toml, authentication, MCP registrations, project trust, databases,
#   and host-context.md, except for an explicit legacy override migration.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOT_HOME="$(cd "$SCRIPT_DIR/.." && pwd)"
CODEX_SOURCE="$DOT_HOME/ai/codex"
CODEX_TARGET_HOME="${CODEX_HOME:-$HOME/.codex}"
OVERRIDE_SOURCE="${DOT_CODEX_OVERRIDE_SOURCE:-}"
GUIDANCE_ONLY=0
MIGRATE_SLURM_OVERRIDE=0

if [[ "$(uname -s)" == "Linux" ]]; then
  INSTALL_HPC_RULES=1
else
  INSTALL_HPC_RULES=0
fi

log()   { printf '\033[1;32m[INFO]\033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m[WARN]\033[0m %s\n' "$*"; }
error() { printf '\033[1;31m[ERR ]\033[0m %s\n' "$*" >&2; }

usage() {
  cat <<'EOF'
Usage: bin/install_codex.sh [options]

Options:
  --hpc                    Install the Linux/HPC hpc.rules policy as well.
  --guidance-only          Link guidance without changing rules or skills.
  --migrate-slurm-override Migrate a reviewed generated Slurm override to host-context.md.
  --override-from PATH     Copy PATH to $CODEX_HOME/AGENTS.override.md.
  --codex-home PATH        Use PATH instead of $HOME/.codex.
  -h, --help               Show this help.

The installer links common AGENTS.md (including server policy), rules and skills.
It never copies config.toml, credentials, MCP state, or project trust files.
An override REPLACES the common AGENTS.md; it is not an additive host policy.
Migration retains the topology block and backs up the obsolete copied body.
Review that body before opting in. Unknown custom overrides are not migrated.
EOF
}

while (( $# > 0 )); do
  case "$1" in
    --hpc)
      INSTALL_HPC_RULES=1
      ;;
    --guidance-only)
      GUIDANCE_ONLY=1
      ;;
    --migrate-slurm-override)
      MIGRATE_SLURM_OVERRIDE=1
      ;;
    --override-from)
      shift
      if (( $# == 0 )); then
        error "--override-from requires a path."
        exit 2
      fi
      OVERRIDE_SOURCE="$1"
      ;;
    --codex-home)
      shift
      if (( $# == 0 )); then
        error "--codex-home requires a path."
        exit 2
      fi
      CODEX_TARGET_HOME="$1"
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      error "Unknown option: $1"
      usage >&2
      exit 2
      ;;
  esac
  shift
done

backup_path() {
  local path="$1" ts backup suffix
  ts="$(date +%Y%m%d_%H%M%S)"
  backup="${path}.bak_${ts}"
  suffix=0
  while [[ -e "$backup" || -L "$backup" ]]; do
    suffix=$((suffix + 1))
    backup="${path}.bak_${ts}_${suffix}"
  done
  mv "$path" "$backup"
  log "Backed up: $path -> $backup"
}

same_path() {
  local left="$1" right="$2"
  [[ "$left" -ef "$right" ]] || [[ "$(readlink "$left" 2>/dev/null || true)" == "$right" ]]
}

ensure_file_link() {
  local src="$1" dst="$2"

  if [[ ! -f "$src" ]]; then
    error "Codex source file is missing: $src"
    exit 1
  fi

  mkdir -p "$(dirname "$dst")"

  if [[ -L "$dst" ]]; then
    if same_path "$dst" "$src"; then
      log "Codex link already up to date: $dst"
      return 0
    fi

    # A broken link to the old managed source is recoverable and can be
    # replaced. An unrelated link belongs to the host and is left untouched.
    if [[ "$(readlink "$dst" 2>/dev/null || true)" != "$src" ]]; then
      warn "Leaving unrelated Codex symlink untouched: $dst -> $(readlink "$dst")"
      return 0
    fi
    rm -f "$dst"
  elif [[ -e "$dst" ]]; then
    backup_path "$dst"
  fi

  ln -s "$src" "$dst"
  log "Linked: $dst -> $src"
}

install_skills() {
  bash "$DOT_HOME/bin/migrate_agent_skills.sh" --codex-home "$CODEX_TARGET_HOME"
}

remove_legacy_server_link() {
  local destination="$CODEX_TARGET_HOME/SERVER.md"
  if [[ -L "$destination" && "$(readlink "$destination")" == "$CODEX_SOURCE/SERVER.md" ]]; then
    rm "$destination"
    log "Removed obsolete managed SERVER.md link; server policy is in AGENTS.md."
  elif [[ -e "$destination" || -L "$destination" ]]; then
    warn "Preserving custom SERVER.md; the shared server policy is already in AGENTS.md."
  fi
}

migrate_slurm_override() {
  python3 - "$CODEX_TARGET_HOME" <<'PY'
import os
from pathlib import Path
import sys
import tempfile
from datetime import datetime

root = Path(sys.argv[1])
source = root / "AGENTS.override.md"
destination = root / "host-context.md"
if not source.exists() and not source.is_symlink():
    print("No legacy override to migrate.")
    raise SystemExit(0)
if source.is_symlink():
    raise SystemExit("Refusing to migrate an override symlink; review its owner first.")
body = source.read_text()
marker = "<!-- Generated by init-slurm-environment. Edit AGENTS.md or rerun the initializer; do not edit this file directly. -->"
begin = "<!-- BEGIN init-slurm-environment -->"
end = "<!-- END init-slurm-environment -->"
if marker not in body or body.count(begin) != 1 or body.count(end) != 1:
    raise SystemExit("Custom or malformed override preserved; review it before migration.")
start = body.index(begin)
stop = body.index(end) + len(end)
if stop <= start:
    raise SystemExit("Malformed topology block; override preserved.")
block = body[start:stop]
if destination.is_symlink():
    raise SystemExit("Host context is a symlink; review it before migration.")
if destination.exists():
    current = destination.read_text()
    if current.count(begin) != 1 or current.count(end) != 1 or block not in current:
        raise SystemExit("Host context differs; both files preserved for review.")
else:
    content = "# Host context\n\nMigrated from the previously audited Slurm override; no new topology audit was run.\n\n" + block + "\n"
    fd, temporary = tempfile.mkstemp(prefix=".host-context-", dir=root)
    with os.fdopen(fd, "w") as stream:
        stream.write(content)
    os.chmod(temporary, 0o644)
    os.replace(temporary, destination)
stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
backup = source.with_name(source.name + ".bak_" + stamp)
suffix = 0
while backup.exists() or backup.is_symlink():
    suffix += 1
    backup = source.with_name(source.name + ".bak_" + stamp + "_" + str(suffix))
source.rename(backup)
print(f"Migrated topology to {destination}; original override saved at {backup}")
PY
}

install_override() {
  local destination="$CODEX_TARGET_HOME/AGENTS.override.md"

  if [[ -z "$OVERRIDE_SOURCE" ]]; then
    if [[ -e "$destination" || -L "$destination" ]]; then
      warn "Preserving $destination; it shadows the common AGENTS.md. Review before migrating."
    else
      log "No AGENTS.override.md created; host facts belong in host-context.md."
    fi
    return 0
  fi

  if [[ ! -f "$OVERRIDE_SOURCE" ]]; then
    error "Override source does not exist: $OVERRIDE_SOURCE"
    exit 1
  fi

  warn "Explicit override installation replaces the common AGENTS.md, rather than extending it."
  mkdir -p "$CODEX_TARGET_HOME"
  if [[ -e "$destination" || -L "$destination" ]]; then
    if cmp -s "$OVERRIDE_SOURCE" "$destination"; then
      log "Codex override already up to date: $destination"
      return 0
    fi
    backup_path "$destination"
  fi

  cp "$OVERRIDE_SOURCE" "$destination"
  chmod 0644 "$destination"
  log "Installed Codex override: $destination"
}

main() {
  if [[ ! -d "$CODEX_SOURCE" ]]; then
    error "Codex files are missing from this checkout: $CODEX_SOURCE"
    exit 1
  fi
  if [[ "$MIGRATE_SLURM_OVERRIDE" == "1" && -n "$OVERRIDE_SOURCE" ]]; then
    error "Choose legacy migration or explicit override installation, not both."
    exit 2
  fi

  mkdir -p "$CODEX_TARGET_HOME"
  if [[ "$MIGRATE_SLURM_OVERRIDE" == "1" ]]; then
    migrate_slurm_override
  fi
  log "Installing repository-managed Codex files into $CODEX_TARGET_HOME"
  ensure_file_link "$CODEX_SOURCE/AGENTS.md" "$CODEX_TARGET_HOME/AGENTS.md"
  remove_legacy_server_link

  if [[ "$GUIDANCE_ONLY" == "1" ]]; then
    log "Guidance-only update: rules and skills unchanged."
  elif [[ "$INSTALL_HPC_RULES" == "1" ]]; then
    ensure_file_link "$CODEX_SOURCE/rules/hpc.rules" "$CODEX_TARGET_HOME/rules/hpc.rules"
  else
    log "Skipping hpc.rules on non-Linux host (pass --hpc to opt in)."
  fi

  if [[ "$GUIDANCE_ONLY" != "1" ]]; then
    install_skills
  fi
  install_override

  cat <<EOF

Codex installation summary
  common guidance: $CODEX_TARGET_HOME/AGENTS.md
  server guidance: included in the common AGENTS.md (applies to server execution)
  host facts: $CODEX_TARGET_HOME/host-context.md (host-local)
  host-local state: config.toml, auth, MCP, trust, databases (unchanged)
EOF
}

main "$@"
